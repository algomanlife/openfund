#!/usr/bin/env node
/**
 * Builds the body of the upstream-watch proposal pull request from files produced earlier in the
 * workflow. Pure text assembly; no network, no repository writes.
 *
 *   node scripts/upstream/watch-proposal.mjs --results watch.json --tests tests.txt [--reports dir] > body.md
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs'
import path from 'node:path'
import { toMarkdown } from './check-releases.mjs'

export function buildBody({ results, tests = '', reports = {} }) {
  const actionable = results.filter((r) => r.status === 'update-available')
  const blocked = actionable.filter((r) => r.action === 'blocked-owner-decision')
  const lines = [
    'Automated **proposal**, not an upgrade. The workflow only refreshed `latest_observed` in `infra/upstream/registry.json`; no pinned version, vendored source, lockfile, Blueprint or deployment changed.',
    '',
    toMarkdown(results),
    '## Test results run by the workflow',
    '',
    tests.trim() ? '```text\n' + tests.trim().slice(0, 6000) + '\n```' : '_No test output captured._',
    '',
  ]
  for (const [id, text] of Object.entries(reports)) lines.push(`<details><summary>Read-only update report: ${id}</summary>`, '', '```text', text.trim().slice(0, 12000), '```', '', '</details>', '')
  lines.push(
    '## Approval required',
    '',
    `- ${actionable.length} provider(s) have updates; ${blocked.length} are majors or otherwise blocked pending an owner decision (${blocked.map((b) => b.name).join(', ') || 'none'}).`,
    '- Merging this PR only records what was observed. To adopt an update, follow the procedure linked in the registry (vendored sources: `Upstream update candidate` workflow or `npm run update:vendor`; Directus: the migration runbook).',
    '- [ ] A maintainer has read the release notes for each provider they intend to adopt',
    '- [ ] Compatibility risk accepted by the owner for any `high` or `blocked-owner-decision` row',
    '',
    '🤖 Generated by the `Upstream watch` workflow.',
  )
  return lines.join('\n') + '\n'
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const a = process.argv.slice(2)
  const arg = (n) => (a.includes(n) ? a[a.indexOf(n) + 1] : null)
  const results = JSON.parse(readFileSync(arg('--results'), 'utf8'))
  const tests = arg('--tests') && existsSync(arg('--tests')) ? readFileSync(arg('--tests'), 'utf8') : ''
  const dir = arg('--reports')
  const reports = dir && existsSync(dir) ? Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.txt')).map((f) => [path.basename(f, '.txt'), readFileSync(path.join(dir, f), 'utf8')])) : {}
  process.stdout.write(buildBody({ results, tests, reports }))
}

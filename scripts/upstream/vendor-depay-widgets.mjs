#!/usr/bin/env node
/**
 * Vendor the official DePay Payment Widget bundle (`@depay/widgets`, MIT).
 *
 *   node scripts/upstream/vendor-depay-widgets.mjs            # verify the vendored file (CI-safe, offline)
 *   node scripts/upstream/vendor-depay-widgets.mjs --update   # download the pinned version from npm
 *
 * The widget's npm package declares React 18 as a peer dependency while the
 * Openfund frontend runs React 19, so it is not installed as a module.
 * Instead the package's self-contained UMD build (`dist/umd/index.bundle.js`,
 * React included, global `DePayWidgets`) is served from Openfund's own origin
 * and loaded on demand by the checkout. The tarball is checked against the
 * npm registry's published sha512 integrity before anything is written, and
 * the Subresource Integrity hash the browser enforces is generated from the
 * exact file.
 */
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const DEPAY_WIDGETS_VERSION = '13.0.45'
/* npm registry `dist.integrity` of @depay/widgets@13.0.45 */
export const DEPAY_WIDGETS_TARBALL_INTEGRITY = 'sha512-Ht+btVTOgtaH4wyJGnomrL7tQg5sogDq9DJy4pzSffxD7xyz0eBUO44zzsbtCHmJWmZsxNhZ+h7nXAQ1GeReTA=='

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const web = path.join(root, 'apps/web-react')
export const bundlePath = path.join(web, `public/assets/vendor/depay-widgets-${DEPAY_WIDGETS_VERSION}.js`)
const licensePath = path.join(web, 'public/assets/notices/DePay-Widgets-MIT.txt')
const manifestPath = path.join(web, 'src/features/purchase/depay-bundle.ts')

const sri = buf => 'sha384-' + createHash('sha384').update(buf).digest('base64')

function manifestSource(integrity) {
  return `/* Generated by scripts/upstream/vendor-depay-widgets.mjs. Do not edit. */
/** Official DePay Payment Widget (@depay/widgets@${DEPAY_WIDGETS_VERSION}, MIT), served same-origin. */
export const DEPAY_WIDGETS_VERSION = '${DEPAY_WIDGETS_VERSION}'
export const DEPAY_WIDGETS_PATH = 'assets/vendor/depay-widgets-${DEPAY_WIDGETS_VERSION}.js'
export const DEPAY_WIDGETS_INTEGRITY = '${integrity}'
`
}

async function update() {
  const meta = await (await fetch(`https://registry.npmjs.org/@depay/widgets/${DEPAY_WIDGETS_VERSION}`)).json()
  if (meta?.dist?.integrity !== DEPAY_WIDGETS_TARBALL_INTEGRITY) throw new Error('registry integrity differs from the pinned value')
  const tgz = Buffer.from(await (await fetch(meta.dist.tarball)).arrayBuffer())
  const got = 'sha512-' + createHash('sha512').update(tgz).digest('base64')
  if (got !== DEPAY_WIDGETS_TARBALL_INTEGRITY) throw new Error('downloaded tarball does not match the pinned integrity')
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'depay-widgets-'))
  try {
    writeFileSync(path.join(tmp, 'p.tgz'), tgz)
    execFileSync('tar', ['xzf', 'p.tgz', 'package/dist/umd/index.bundle.js', 'package/LICENSE'], { cwd: tmp })
    const bundle = readFileSync(path.join(tmp, 'package/dist/umd/index.bundle.js'))
    mkdirSync(path.dirname(bundlePath), { recursive: true })
    writeFileSync(bundlePath, bundle)
    writeFileSync(licensePath, `@depay/widgets ${DEPAY_WIDGETS_VERSION} — https://github.com/DePayFi/widgets\n\n` + readFileSync(path.join(tmp, 'package/LICENSE'), 'utf8'))
    writeFileSync(manifestPath, manifestSource(sri(bundle)))
    console.log(`vendored @depay/widgets@${DEPAY_WIDGETS_VERSION} (${bundle.length} bytes, ${sri(bundle)})`)
  } finally { rmSync(tmp, { recursive: true, force: true }) }
}

function verify() {
  const bundle = readFileSync(bundlePath)
  const manifest = readFileSync(manifestPath, 'utf8')
  if (manifest !== manifestSource(sri(bundle))) throw new Error('depay-bundle.ts does not match the vendored bundle — run with --update')
  if (!bundle.subarray(0, 400).toString().includes('DePayWidgets')) throw new Error('vendored file is not the DePayWidgets UMD bundle')
  readFileSync(licensePath)
  console.log(`DePay widget bundle ${DEPAY_WIDGETS_VERSION} verified (${sri(bundle)})`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  ;(process.argv.includes('--update') ? update() : Promise.resolve(verify())).catch(e => { console.error(e.message); process.exit(1) })
}

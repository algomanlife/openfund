import test from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { run, parseSemver, bumpClass, changelogBetween } from '../update-vendor.mjs'

const g = (cwd, ...a) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', ...a], { cwd, encoding: 'utf8', stdio: 'pipe' })
const put = (root, f, t) => { mkdirSync(path.dirname(path.join(root, f)), { recursive: true }); writeFileSync(path.join(root, f), t) }
const quiet = async (fn) => { const l = console.log, e = console.error; console.log = () => {}; console.error = () => {}; try { return await fn() } finally { console.log = l; console.error = e } }

/** A fake "upstream" with two tags, and a fake Openfund checkout that vendors v1.0.0 plus one patch. */
function fixture({ conflicting = false, localEdit = false } = {}) {
  const up = mkdtempSync(path.join(os.tmpdir(), 'of-fake-up-'))
  g(up, 'init', '-q', '-b', 'main')
  put(up, 'package.json', JSON.stringify({ name: 'fake', version: '1.0.0', dependencies: {} }))
  put(up, 'LICENSE', 'Apache\n'); put(up, 'NOTICE', 'Attribution one\n')
  put(up, 'src/menu.ts', 'line1\nline2\nline3\nline4\nline5\n')
  put(up, 'src/other.ts', 'other\n')
  put(up, 'CHANGELOG.md', '## [1.0.0]\n\nfirst\n')
  g(up, 'add', '-A'); g(up, 'commit', '-qm', 'v1'); g(up, 'tag', 'v1.0.0')
  const base = g(up, 'rev-parse', 'HEAD').trim()
  put(up, 'package.json', JSON.stringify({ name: 'fake', version: '1.1.0', dependencies: { x: '1' } }))
  put(up, 'src/other.ts', 'other changed\n')
  put(up, 'src/menu.ts', conflicting ? 'line1\nLINE2 REWRITTEN\nline3\nline4\nline5\n' : 'line1\nline2\nline3\nline4\nline5\nline6\n')
  put(up, 'NOTICE', 'Attribution changed\n')
  put(up, 'CHANGELOG.md', '## [1.1.0]\n\n### BREAKING\n\n- something\n\n## [1.0.0]\n\nfirst\n')
  g(up, 'add', '-A'); g(up, 'commit', '-qm', 'v1.1'); g(up, 'tag', 'v1.1.0')

  const root = mkdtempSync(path.join(os.tmpdir(), 'of-fake-root-'))
  g(up, 'checkout', '-q', 'v1.0.0')
  for (const f of ['package.json', 'LICENSE', 'NOTICE', 'src/menu.ts', 'src/other.ts', 'CHANGELOG.md']) put(root, `vendor/fake/${f}`, readFileSync(path.join(up, f), 'utf8'))
  g(up, 'checkout', '-q', 'main')
  const patched = 'line1\nline2 OPENFUND\nline3\nline4\nline5\n'
  put(root, 'vendor/fake/src/menu.ts', localEdit ? patched : 'line1\nline2\nline3\nline4\nline5\n')
  if (!localEdit) {
    /* register a real patch generated by git */
    const tmp = mkdtempSync(path.join(os.tmpdir(), 'of-fake-gen-'))
    g(tmp, 'init', '-q'); put(tmp, 'src/menu.ts', 'line1\nline2\nline3\nline4\nline5\n'); g(tmp, 'add', '-A'); g(tmp, 'commit', '-qm', 'b')
    put(tmp, 'src/menu.ts', patched)
    put(root, 'infra/upstream/patches/fake-1.0.0/0001-menu.patch', g(tmp, 'diff', '--', 'src/menu.ts'))
    put(root, 'vendor/fake/src/menu.ts', patched)
    rmSync(tmp, { recursive: true, force: true })
  }
  const registry = { providers: [{ id: 'fake', name: 'Fake', kind: 'vendored-source', installed: { version: '1.0.0', ref: base, path: 'vendor/fake', manifest: 'vendor/fake/package.json' }, update: { repo_url: up, tag_prefix: 'v', subdir: '', vendor_path: 'vendor/fake', patch_dir: 'infra/upstream/patches/fake-{version}' } }] }
  put(root, 'infra/upstream/registry.json', JSON.stringify(registry))
  put(root, 'infra/upstream/patches.json', JSON.stringify({ patches: [{ id: 'F1', provider: 'fake', affected_version: '1.0.0', kind: 'source', patch_file: 'infra/upstream/patches/fake-1.0.0/0001-menu.patch' }] }))
  return { up, root, cleanup: () => { rmSync(up, { recursive: true, force: true }); rmSync(root, { recursive: true, force: true }) } }
}

test('helpers classify versions and slice changelogs', () => {
  assert.deepEqual(parseSemver('v0.10.4'), [0, 10, 4]); assert.equal(parseSemver('main'), null)
  assert.equal(bumpClass([0, 9, 3], [0, 10, 4]), 'minor'); assert.equal(bumpClass([1, 0, 0], [2, 0, 0]), 'major')
  assert.match(changelogBetween('## [1.1.0]\nnew\n## [1.0.0]\nold\n', '1.0.0', '1.1.0'), /new/)
})

test('report mode flags risk and legal changes and writes nothing', async () => {
  const f = fixture()
  try {
    const before = readFileSync(path.join(f.root, 'vendor/fake/src/menu.ts'), 'utf8')
    const r = await quiet(() => run(['--provider', 'fake', '--root', f.root, '--to', 'v1.1.0']))
    assert.equal(r.code, 0)
    assert.match(r.log.join('\n'), /IDENTICAL/); assert.match(r.log.join('\n'), /NOTICE changed: LEGAL REVIEW/); assert.match(r.log.join('\n'), /changelog mentions BREAKING/)
    assert.match(r.log.join('\n'), /1 clean, 0 conflict/)
    assert.equal(readFileSync(path.join(f.root, 'vendor/fake/src/menu.ts'), 'utf8'), before)
  } finally { f.cleanup() }
})

test('--apply writes the new upstream with Openfund patches preserved and regenerated', async () => {
  const f = fixture()
  try {
    const r = await quiet(() => run(['--provider', 'fake', '--root', f.root, '--to', 'v1.1.0', '--apply']))
    assert.equal(r.code, 0)
    const menu = readFileSync(path.join(f.root, 'vendor/fake/src/menu.ts'), 'utf8')
    assert.match(menu, /line2 OPENFUND/, 'customization preserved'); assert.match(menu, /line6/, 'upstream change taken')
    assert.equal(readFileSync(path.join(f.root, 'vendor/fake/src/other.ts'), 'utf8'), 'other changed\n')
    const reg = JSON.parse(readFileSync(path.join(f.root, 'infra/upstream/registry.json'), 'utf8')).providers[0]
    assert.equal(reg.installed.version, '1.1.0'); assert.equal(reg.compatibility.status, 'candidate-unreviewed')
    assert.ok(existsSync(path.join(f.root, 'infra/upstream/patches/fake-1.1.0/0001-menu.patch')))
    assert.ok(!existsSync(path.join(f.root, 'infra/upstream/patches/fake-1.0.0')))
    const patches = JSON.parse(readFileSync(path.join(f.root, 'infra/upstream/patches.json'), 'utf8')).patches[0]
    assert.equal(patches.affected_version, '1.1.0'); assert.match(patches.patch_file, /fake-1\.1\.0/)
  } finally { f.cleanup() }
})

test('a conflicting upstream change aborts without touching the working tree', async () => {
  const f = fixture({ conflicting: true })
  try {
    const before = readFileSync(path.join(f.root, 'vendor/fake/src/menu.ts'), 'utf8')
    const r = await quiet(() => run(['--provider', 'fake', '--root', f.root, '--to', 'v1.1.0', '--apply']))
    assert.equal(r.code, 2)
    assert.match(r.log.join('\n'), /CONFLICT 0001-menu\.patch/); assert.match(r.log.join('\n'), /also changed 1 file\(s\) that Openfund patches/)
    assert.equal(readFileSync(path.join(f.root, 'vendor/fake/src/menu.ts'), 'utf8'), before)
    assert.equal(JSON.parse(readFileSync(path.join(f.root, 'infra/upstream/registry.json'), 'utf8')).providers[0].installed.version, '1.0.0')
  } finally { f.cleanup() }
})

test('an undocumented local edit to the vendored tree stops the update', async () => {
  const f = fixture({ localEdit: true })
  try {
    const r = await quiet(() => run(['--provider', 'fake', '--root', f.root, '--to', 'v1.1.0', '--apply']))
    assert.equal(r.code, 2)
    assert.match(r.log.join('\n'), /MISMATCH/); assert.match(r.log.join('\n'), /undocumented difference: src\/menu\.ts/)
  } finally { f.cleanup() }
})

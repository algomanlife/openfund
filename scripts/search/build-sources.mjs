#!/usr/bin/env node
/* Builds apps/backend/search-sources.json, the bundled part of the site
 * search index (ADR 0052): public routes from editorialRoutes.ts with their
 * menu labels and descriptions, and the developer documentation sections.
 * The backend stays self-contained (the Iran image is built from the release
 * archive), so these sources are generated here and committed.
 *
 *   node scripts/search/build-sources.mjs          write the file
 *   node scripts/search/build-sources.mjs --check  fail when it is stale
 *
 * Added locales (ar, ru, zh-CN) use the reviewed dictionaries in
 * apps/web-react/src/i18n/content/; a missing entry falls back to English,
 * exactly like the web app. Nothing is machine translated. */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const out = path.join(root, 'apps/backend/search-sources.json')
const ADDED = ['ar', 'ru', 'zh-CN']

const { EDITORIAL_ROUTES } = await import(path.join(root, 'apps/web-react/src/cms/editorialRoutes.ts'))
const dictionaries = Object.fromEntries(ADDED.map(l => [l, JSON.parse(read(`apps/web-react/src/i18n/content/${l}.json`))]))

/* `key: text('English', 'فارسی')` pairs inside one exported object literal */
function textPairs(file, start) {
  const src = read(file)
  const from = src.indexOf(start)
  if (from < 0) throw new Error(`${start} not found in ${file}`)
  const block = src.slice(from, src.indexOf('\n}', from))
  const pairs = {}
  const re = /^\s*'?([\w-]+)'?:\s*text\('((?:\\'|[^'])*)',\s*'((?:\\'|[^'])*)'\)/gm
  for (const m of block.matchAll(re)) pairs[m[1]] = { en: m[2].replace(/\\'/g, "'"), fa: m[3].replace(/\\'/g, "'") }
  return pairs
}
const localized = pair => pair && { fa: pair.fa, en: pair.en, ...Object.fromEntries(ADDED.map(l => [l, dictionaries[l][pair.en] || pair.en])) }

const labels = textPairs('apps/web-react/src/features/information/content.ts', 'export const labels')
const descriptions = textPairs('apps/web-react/src/features/navigation/megaMenu.ts', 'export const MEGA_DESCRIPTIONS')
const icons = new Set([...read('apps/web-react/src/features/navigation/megaMenu.ts').matchAll(/^\s*'?([\w-]+)'?: 'M/gm)].map(m => m[1]))

const routes = []
for (const r of EDITORIAL_ROUTES) {
  if (!/^\/:locale\/[a-z0-9/-]+$/.test(r.path)) continue /* only fixed public paths */
  if (r.path === '/:locale/search') continue /* the results page itself */
  const key = r.path.slice('/:locale/'.length)
  const label = labels[key] || (r.view === key ? labels[r.view] : null)
  if (!label) continue /* no menu label: not a destination people search for */
  routes.push({ path: key, view: r.view, icon: icons.has(r.view) ? r.view : icons.has(key) ? key : null,
    title: localized(label), description: localized(descriptions[r.view] || descriptions[key]) || null })
}

const en = JSON.parse(read('docs/developer-portal/sections.json')).sections
const fa = JSON.parse(read('apps/web-react/src/features/developers/sections.fa.json'))
const plain = md => String(md || '').replace(/```[\s\S]*?```/g, ' ').replace(/`([^`]*)`/g, '$1').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
  .replace(/[#>*_|-]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 600)
const docs = en.filter(s => s.status === 'published').map(s => ({
  slug: s.slug, title: { en: s.title, fa: fa[s.slug]?.title || s.title }, text: { en: plain(s.body), fa: plain(fa[s.slug]?.body || s.body) },
}))

const body = JSON.stringify({ note: 'Generated by scripts/search/build-sources.mjs. Do not edit by hand.', routes, docs }, null, 2) + '\n'
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (current !== body) { console.error('apps/backend/search-sources.json is stale: run node scripts/search/build-sources.mjs'); process.exit(1) }
  console.log(`search sources current: ${routes.length} routes, ${docs.length} developer doc sections`)
} else {
  fs.writeFileSync(out, body)
  console.log(`wrote apps/backend/search-sources.json: ${routes.length} routes, ${docs.length} developer doc sections`)
}

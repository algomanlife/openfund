#!/usr/bin/env node
/* Production dependency license inventory (docs/legal/DEPENDENCY_LICENSES.md).
   Reads the per-app lockfiles only (no network, no node_modules needed), lists
   every non-dev package whose declared license is NOT a common permissive
   license, for legal review. Licenses missing from
   a lockfile are taken from REVIEWED below (each read from the package's own
   files). `--check` fails when the committed inventory is stale, so CI keeps
   it in sync with the lockfiles. It never edits anything in check mode. */
import fs from 'node:fs'

const OUT = 'docs/legal/DEPENDENCY_LICENSES.md'
const APPS = [['apps/web-react', 'Web application (shipped to browsers)'], ['apps/backend', 'Backend API (server-side, not distributed)']]
const PERMISSIVE = /^(\(?)(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|CC0-1\.0|Unlicense|BlueOak-1\.0\.0|Python-2\.0|CC-BY-4\.0|WTFPL)( (OR|AND) (MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|CC0-1\.0))*\)?$/
/* licenses absent from the lockfile, read manually from the package files (2026-11-10) */
const REVIEWED = {
  '@metamask/sdk': 'LicenseRef-ConsenSys-NonCommercial (see notice)',
  '@metamask/sdk-communication-layer': 'LicenseRef-ConsenSys-NonCommercial (see notice)',
  '@metamask/sdk-install-modal-web': 'LicenseRef-ConsenSys-NonCommercial (see notice)',
  '@metamask/eth-json-rpc-provider': 'UNDECLARED (no license field or file in the package)',
  'xmlhttprequest-ssl': 'MIT',
}

function inventory(app) {
  const lock = JSON.parse(fs.readFileSync(`${app}/package-lock.json`, 'utf8'))
  const rows = new Map()
  for (const [key, v] of Object.entries(lock.packages || {})) {
    if (!key || v.dev || v.devOptional || v.link) continue
    const name = key.split('node_modules/').pop()
    const license = (typeof v.license === 'string' && v.license) || REVIEWED[name] || 'UNDECLARED'
    rows.set(`${name}@${v.version}`, { name, version: v.version, license })
  }
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || String(a.version).localeCompare(String(b.version)))
}

let md = `# Production dependency licenses

Generated by \`node scripts/legal/dependency-licenses.mjs\` from the per-app
lockfiles. \`npm run docs:check\` verifies it is current. Development-only
packages are excluded. This is an engineering inventory, not legal advice; see
[Licensing](LICENSING.md) for obligations and open decisions.

`
for (const [app, label] of APPS) {
  const rows = inventory(app)
  const review = rows.filter(r => !PERMISSIVE.test(r.license))
  /* only the review-relevant packages are committed, so routine bumps of
     permissively licensed packages (Dependabot) never make this stale */
  md += `## ${label}: \`${app}\`\n\nEvery other production package declares a common permissive license (MIT, ISC, Apache-2.0, BSD, 0BSD, CC0 and similar).\n\n### Needs legal review (${review.length})\n\n`
  md += review.length ? '| Package | Version | License |\n| --- | --- | --- |\n' + review.map(r => `| \`${r.name}\` | ${r.version} | ${r.license} |`).join('\n') + '\n\n' : 'None.\n\n'
}
md = md.replace(/\n+$/, '\n')

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== md) { console.error(`${OUT} is stale — run node scripts/legal/dependency-licenses.mjs and commit the result`); process.exit(1) }
  console.log(`legal:licenses OK — ${OUT} matches the lockfiles`)
} else {
  fs.writeFileSync(OUT, md)
  console.log(`wrote ${OUT}`)
}
